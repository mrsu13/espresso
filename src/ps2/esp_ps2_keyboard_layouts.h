#pragma once


/**
 * @file
 *
 * @brief This file contains keyboard layouts
 */


#include <stdint.h>

#include "esp_ps2_utils.h"
#include "esp_tools.h"


namespace esp::ps2
{


/**
 * @brief Associates scancode to virtualkey.
 */
struct virtual_key_def
{
    uint8_t scancode; /**< Raw scancode received from the Keyboard device */
    esp::ps2::virtual_key
        virtual_key; /**< Real virtualkey (non shifted) associated to the scancode */
};


/**
 * @brief Associates a virtualkey and various shift states (ctrl, alt, etc..) to another virtualkey.
 */
struct alt_virtual_key_def
{
    esp::ps2::virtual_key req_virtual_key; /**< Source virtualkey translated using VirtualKeyDef. */
    struct
    {
        uint8_t ctrl : 1; /**< CTRL needs to be down. */
        uint8_t lalt : 1; /**< LEFT-ALT needs to be down. */
        uint8_t ralt : 1; /**< RIGHT-ALT needs to be down. */
        uint8_t shift : 1; /**< SHIFT needs to be down (OR-ed with capslock). */
    };
    esp::ps2::virtual_key virtual_key; /**< Generated virtualkey. */
};


struct dead_key_virtual_key_def
{
    esp::ps2::virtual_key dead_key; /**< Currently pressed dead key */
    esp::ps2::virtual_key req_virtual_key; /**< Currently pressed virtual key */
    esp::ps2::virtual_key virtual_key; /**< Virtual key result */
};


/** @brief All in one structure to fully represent a keyboard layout */
struct keyboard_layout
{
    const char *name; /**< Layout name. */
    const char *desc; /**< Layout description. */
    keyboard_layout const *
        inherited; /**< Inherited layout. Useful to avoid to repeat the same scancode-virtualkeys associations. */
    virtual_key_def scancode_to_vk[86]; /**< Direct one-byte-scancode->virtualkey associations. */
    virtual_key_def ex_scancode_to_vk
        [22]; /**< Direct extended-scancode->virtualkey associations. Extended scancodes begin with 0xE0. */
    alt_virtual_key_def
        alternate_vk[73]; /**< Virtualkeys generated by other virtualkeys and shift combinations. */

    virtual_key dead_keys_vk[8]; /**< Dead keys identifiers. */
    dead_key_virtual_key_def
        deadkeys_to_vk[60]; /**< Translation dead key + virtual key = replaced virtual key */
};


/** @brief Predefined US layout. Often used as inherited layout for other layouts. */
extern const keyboard_layout US_LAYOUT;

/** @brief UK keyboard layout */
extern const keyboard_layout UK_LAYOUT;

/** @brief German keyboard layout */
extern const keyboard_layout GERMAN_LAYOUT;

/** @brief Italian keyboard layout */
extern const keyboard_layout ITALIAN_LAYOUT;

/** @brief Spanish keyboard layout */
extern const keyboard_layout SPANISH_LAYOUT;

/** @brief French keyboard layout */
extern const keyboard_layout FRENCH_LAYOUT;

/** @brief Belgian keyboard layout */
extern const keyboard_layout BELGIAN_LAYOUT;

/** @brief Norwegian keyboard layout */
extern const keyboard_layout NORWEGIAN_LAYOUT;

/** @brief Japanese keyboard layout */
extern const keyboard_layout JAPANESE_LAYOUT;


struct supported_layouts
{

    static constexpr int LAYOUTSCOUNT = 9;

    static int count()
    {
        return LAYOUTSCOUNT;
    }

    static char const **names()
    {
        static char const *NAMES[LAYOUTSCOUNT] = {
            GERMAN_LAYOUT.desc,  ITALIAN_LAYOUT.desc,   UK_LAYOUT.desc,
            US_LAYOUT.desc,      SPANISH_LAYOUT.desc,   FRENCH_LAYOUT.desc,
            BELGIAN_LAYOUT.desc, NORWEGIAN_LAYOUT.desc, JAPANESE_LAYOUT.desc,
        };
        return NAMES;
    }

    static char const **short_names()
    {
        static char const *SNAMES[LAYOUTSCOUNT] = {
            GERMAN_LAYOUT.name,  ITALIAN_LAYOUT.name,   UK_LAYOUT.name,
            US_LAYOUT.name,      SPANISH_LAYOUT.name,   FRENCH_LAYOUT.name,
            BELGIAN_LAYOUT.name, NORWEGIAN_LAYOUT.name, JAPANESE_LAYOUT.name,
        };
        return SNAMES;
    }

    static const keyboard_layout **layouts()
    {
        static keyboard_layout const *LAYOUTS[LAYOUTSCOUNT] = {
            &GERMAN_LAYOUT, &ITALIAN_LAYOUT, &UK_LAYOUT,        &US_LAYOUT,       &SPANISH_LAYOUT,
            &FRENCH_LAYOUT, &BELGIAN_LAYOUT, &NORWEGIAN_LAYOUT, &JAPANESE_LAYOUT,
        };
        return LAYOUTS;
    }
};


} // end of namespace
