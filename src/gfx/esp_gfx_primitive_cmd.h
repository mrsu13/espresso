#pragma once


/**
 * @file
 * @brief Команды примитивов рисования esp::gfx::primitive_cmd.
 */


#include <cstdint>


namespace esp::gfx
{

/**
 * @brief Команда примитива рисования @c esp::gfx::primitive.
 *
 * В описании каждой команды указано, какое поле примитива служит её
 * параметром. Координаты задаются относительно начала координат холста и
 * могут выходить за экран: фигуры обрезаются областью отсечения.
 */
enum class primitive_cmd : std::uint8_t
{
    /** @brief Отметить область как изменённую, чтобы её перерисовали спрайты; параметр @c rect. */
    refresh,

    /** @brief Вернуть параметры рисования к начальным (esp::gfx::paint_state); без параметра. */
    reset,

    /** @brief Задать цвет пера; параметр @c color. */
    set_pen_color,

    /** @brief Задать цвет кисти; параметр @c color. */
    set_brush_color,

    /** @brief Нарисовать точку цветом пера; параметр @c position. */
    set_pixel,

    /** @brief Нарисовать точку заданным цветом; параметр @c pixel_desc. */
    set_pixel_at,

    /** @brief Перенести текущую позицию; параметр @c position. */
    move_to,

    /** @brief Провести линию пером от текущей позиции и перенести туда позицию; параметр @c position. */
    line_to,

    /** @brief Залить прямоугольник кистью; параметр @c rect. */
    fill_rect,

    /** @brief Нарисовать рамку прямоугольника пером; параметр @c rect. */
    draw_rect,

    /** @brief Залить эллипс кистью с центром в текущей позиции; параметр @c size. */
    fill_ellipse,

    /** @brief Нарисовать эллипс пером с центром в текущей позиции; параметр @c size. */
    draw_ellipse,

    /** @brief Залить всю область вывода кистью; без параметра. */
    clear,

    /**
     * @brief Прокрутить область прокрутки по вертикали; параметр @c ivalue.
     *
     * Отрицательное значение — вверх, положительное — вниз. Строки буфера
     * переставляются, а не копируются, поэтому прокрутка быстрая.
     */
    v_scroll,

    /**
     * @brief Прокрутить область прокрутки по горизонтали; параметр @c ivalue.
     *
     * Отрицательное значение — влево, положительное — вправо. Пиксели
     * копируются по одному, поэтому прокрутка медленная.
     */
    h_scroll,

    /** @brief Нарисовать знак с текущими параметрами знаков; параметр @c glyph. */
    draw_glyph,

    /** @brief Задать параметры рисования знаков; параметр @c glyph_options. */
    set_glyph_options,

    /** @brief Задать общие параметры рисования; параметр @c paint_options. */
    set_paint_options,

    /** @brief Инвертировать пиксели прямоугольника; параметр @c rect. */
    invert_rect,

    /** @brief Скопировать прямоугольник в текущую позицию, области могут перекрываться; параметр @c rect. */
    copy_rect,

    /** @brief Задать область прокрутки; параметр @c rect. */
    set_scrolling_region,

    /**
     * @brief Поменять цвета пера и кисти в прямоугольнике; параметр @c rect.
     *
     * Пиксели цвета пера становятся цвета кисти и наоборот; остальные
     * цвета не меняются.
     */
    swap_fgbg,

    /** @brief Нарисовать растр; параметр @c bitmap_drawing_info. */
    draw_bitmap,

    /** @brief Перерисовать спрайты; без параметра. */
    refresh_sprites,

    /**
     * @brief Поменять местами буферы кадра; параметр @c notify_task.
     *
     * Только в режиме двойной буферизации. Выполнив команду, контроллер
     * будит ждущую задачу @c notify_task.
     */
    swap_buffers,

    /** @brief Залить многоугольник кистью; параметр @c path. */
    fill_path,

    /** @brief Нарисовать многоугольник пером; параметр @c path. */
    draw_path,

    /** @brief Задать начало координат; параметр @c position. */
    set_origin,

    /** @brief Задать область отсечения относительно начала координат; параметр @c rect. */
    set_clipping_rect,

    /** @brief Задать толщину пера; параметр @c ivalue. */
    set_pen_width,

    /** @brief Задать форму концов толстых линий; параметр @c line_ends. */
    set_line_ends,
};

}
