/**
 * @file esp_gfx_rgb888.cpp
 * @brief 24-разрядный цвет: перевод именованных цветов.
 */

#include "esp_gfx_rgb888.h"


#pragma GCC optimize("O2")


namespace esp::gfx::p
{

/**
 * @brief Каналы шестнадцати именованных цветов в порядке @c esp::gfx::color.
 *
 * Тёмные цвета используют уровень 128, яркие — 255, серый
 * @c esp::gfx::color::bright_black — 64.
 */
constexpr esp::gfx::rgb888 COLOR_TO_RGB888[16] = {
    {0, 0, 0}, // Чёрный.
    {128, 0, 0}, // Красный.
    {0, 128, 0}, // Зелёный.
    {128, 128, 0}, // Жёлтый.
    {0, 0, 128}, // Синий.
    {128, 0, 128}, // Пурпурный.
    {0, 128, 128}, // Бирюзовый.
    {128, 128, 128}, // Белый.
    {64, 64, 64}, // Тёмно-серый.
    {255, 0, 0}, // Ярко-красный.
    {0, 255, 0}, // Ярко-зелёный.
    {255, 255, 0}, // Ярко-жёлтый.
    {0, 0, 255}, // Ярко-синий.
    {255, 0, 255}, // Ярко-пурпурный.
    {0, 255, 255}, // Ярко-бирюзовый.
    {255, 255, 255}, // Ярко-белый.
};

}


/**
 * @struct esp::gfx::rgb888
 * @brief Цвет из трёх 8-разрядных каналов: красного, зелёного и синего.
 *
 * Каждый канал — от 0 до 255. В таком виде цвета задают перо и кисть
 * холста; контроллер дисплея переводит их в свой формат пикселя, отбрасывая
 * младшие разряды. Структура упакована (3 байта), потому что входит в
 * примитив рисования @c esp::gfx::primitive.
 */


// Открытые

/**
 * @brief Создаёт цвет по имени.
 * @param color Именованный цвет; каналы берутся из таблицы цветов модуля.
 */
esp::gfx::rgb888::rgb888(color color)
{
    *this = esp::gfx::p::COLOR_TO_RGB888[static_cast<int>(color)];
}
