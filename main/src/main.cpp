/**
 * @mainpage Espresso
 *
 * Прошивка для платы LilyGO TTGO T-Display (ESP32, ESP-IDF 6.1). При
 * запуске она выводит в последовательную консоль сведения о плате, затем
 * опрашивает обе кнопки: каждое нажатие включает или выключает экран.
 *
 * Приложение — класс esp::app. Оборудование представлено классами
 * esp::backlight (подсветка), esp::button (кнопка), esp::display (дисплей)
 * и esp::sd_card (карта памяти); корпус чипа определяет esp::chip_package().
 */

/**
 * @namespace esp
 * @brief Классы и функции прошивки Espresso.
 */

#include "esp_app.h"


/**
 * @brief Точка входа приложения ESP-IDF.
 *
 * Вызывается из главной задачи FreeRTOS после запуска системы. Создаёт
 * приложение и передаёт ему управление.
 */
extern "C" void app_main()
{
    // Приложение живёт на стеке главной задачи: exec() не возвращает
    // управление, поэтому объект не разрушается.
    esp::app app;
    app.exec();
}
