namespace esp::vt
{

/**
 * @brief Получатель прерывания: ему терминал передаёт Ctrl+C.
 *
 * Терминал вызывает interrupt(), когда приходит Ctrl+C или прерывание
 * подаёт программа (esp::vt::terminal::interrupt()). Принятое прерывание
 * в ввод не попадает, а непрочитанный ввод терминал сбрасывает; иначе
 * Ctrl+C — обычный байт ввода 0x03. Оболочка Форта принимает прерывание,
 * пока выполняется код Форта (раздел 7.6 документа об устройстве).
 */
class interrupt_handler
{

public:

    virtual ~interrupt_handler() = default;

    virtual bool interrupt() = 0;
};

}


