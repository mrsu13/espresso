/**
 * @brief Всегда встраивать функцию, в том числе метод класса.
 *
 * FORCE_INLINE_ATTR из ESP-IDF содержит @c static и для методов класса не
 * годится. Встраивание обязательно для функций, которые вызывает код в
 * IRAM: отдельная копия функции оказалась бы во флеш-памяти, недоступной
 * при записи во флеш-память.
 */
#define ESP_ALWAYS_INLINE_ATTR __attribute__((always_inline))
