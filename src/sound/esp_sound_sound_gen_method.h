#pragma once


/**
 * @file
 * @brief Способ вывода звука esp::sound::sound_gen_method.
 */


namespace esp::sound
{

/**
 * @brief Способ, которым генератор звука выводит отсчёты.
 *
 * Задаётся при создании генератора звука esp::sound::sound_generator и
 * вместе с выводом GPIO определяет, какое оборудование ESP32 занимает
 * звук: встроенный ЦАП с модулем I2S0 или сигма-дельта-модулятор с
 * таймером.
 */
enum class sound_gen_method
{
    /**
     * @brief Встроенный ЦАП, на который отсчёты подаёт модуль I2S0 по DMA.
     *
     * Работает только на выводах GPIO25 (ЦАП 1) и GPIO26 (ЦАП 2) и почти не
     * нагружает процессор: обработчик прерывания заполняет буфер DMA раз в
     * @c esp::sound::SAMPLE_BUFFER_SIZE отсчётов. Занимает модуль I2S0.
     */
    dac,

    /**
     * @brief Сигма-дельта-модулятор, которому таймер подаёт отсчёт за отсчётом.
     *
     * Работает почти на любом выводе GPIO, но обработчик таймера вызывается
     * на каждый отсчёт, и при высокой частоте дискретизации нагрузка на
     * процессор велика.
     */
    sigma_delta,

    /**
     * @brief Выбор по видеовыходу при первом запуске звука.
     *
     * Если текущий видеовыход (@c esp::current_video_mode) композитный,
     * выбирается сигма-дельта-модулятор, иначе — ЦАП.
     */
    automatic,
};

}
