#pragma once


/**
 * @file
 * @brief Настройки модуля звука esp::sound.
 */


#include <cstddef>


namespace esp::sound
{

/**
 * @brief Частота дискретизации генератора звука по умолчанию, Гц.
 *
 * С ней создаётся @c esp::sound::sound_generator, если частота не задана
 * явно. В режиме ЦАП действительная частота немного отличается: делители
 * тактовой частоты I2S подбираются к заданной как можно точнее.
 */
constexpr int DEFAULT_SAMPLE_RATE = 16384;

/**
 * @brief Число отсчётов в каждом из двух буферов DMA в режиме ЦАП.
 *
 * Когда буфер выведен, обработчик прерывания I2S заполняет его заново,
 * поэтому от размера буфера зависит частота прерываний: 64 отсчёта при
 * 16 кГц дают 250 прерываний в секунду.
 */
constexpr int SAMPLE_BUFFER_SIZE = 64;

/**
 * @brief Число голосов генератора звука: столько его собственных звуков могут звучать одновременно.
 *
 * Генераторы волны, которые создают esp::sound::sound_generator::play_sound()
 * и esp::sound::sound_generator::play_samples(), живут в голосах — местах
 * внутри генератора звука, — а не в динамической памяти. Голос
 * освобождается, когда его звук отзвучал или отключён; если свободных
 * голосов нет, новый звук не запускается.
 */
constexpr int VOICE_COUNT = 8;

/**
 * @brief Место под генератор волны в одном голосе, байты.
 *
 * Не меньше размера самого большого генератора, который запускают через
 * esp::sound::sound_generator::play_sound(): встроенные генераторы волны
 * занимают до 32 байтов. С большим генератором play_sound() не
 * скомпилируется — размер проверяет @c static_assert. Значение кратно
 * выравниванию @c std::max_align_t, чтобы каждый голос был выровнен для
 * любого типа.
 */
constexpr std::size_t VOICE_SIZE = 32;

}
