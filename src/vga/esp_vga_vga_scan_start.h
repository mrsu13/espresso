#pragma once


/**
 * @file
 * @brief Начальный участок строки развёртки esp::vga::vga_scan_start.
 */


namespace esp::vga
{

/**
 * @brief С какого участка начинается строка развёртки в буфере DMA.
 *
 * Строка состоит из четырёх участков: переднего гасящего интервала, синхроимпульса,
 * заднего гасящего интервала и видимой части; они идут по кругу, а этот
 * параметр задаёт, какой из них первый. Некоторым мониторам важен порядок.
 */
enum class vga_scan_start : unsigned
{
    /** @brief Передний гасящий интервал, синхроимпульс, задний гасящий интервал, видимая часть. */
    front_porch,

    /** @brief Синхроимпульс, задний гасящий интервал, видимая часть, передний гасящий интервал. */
    sync,

    /** @brief Задний гасящий интервал, видимая часть, передний гасящий интервал, синхроимпульс. */
    back_porch,

    /** @brief Видимая часть, передний гасящий интервал, синхроимпульс, задний гасящий интервал. */
    visible_area,
};

}
