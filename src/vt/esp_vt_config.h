#pragma once


/**
 * @file
 * @brief Настройки терминала esp::vt: пределы разборщика, размер экрана, цвета.
 */


#include <array>
#include <cstdint>


namespace esp::vt
{

/**
 * @brief Наибольшее число числовых параметров одной последовательности CSI.
 *
 * Хватает с запасом всем последовательностям, которые понимает экран: у самой
 * длинной из них, @c SGR с цветом @c 38;2;r;g;b и несколькими признаками,
 * около десятка параметров. Лишние параметры разборщик отбрасывает, поэтому
 * слишком длинная последовательность не выходит за массив параметров.
 */
constexpr int MAX_PARAMS = 16;

/**
 * @brief Наибольшее число промежуточных байтов (0x20–0x2F) одной последовательности.
 *
 * В VT220 их бывает не больше двух; лишние разборщик отбрасывает.
 */
constexpr int MAX_INTERMEDIATES = 2;

/**
 * @brief Наибольшее значение числового параметра.
 *
 * Больший параметр разборщик урезает до этого значения, как xterm: иначе
 * последовательность вроде @c CSI 99999999999m переполнила бы целое число, и
 * в расчёт положения курсора попал бы отрицательный параметр.
 */
constexpr int MAX_PARAM_VALUE = 65535;

/**
 * @brief Знак замены U+FFFD.
 *
 * Им разборщик заменяет испорченную последовательность UTF-8, а экран — знак
 * за пределами основной плоскости Unicode: такой код в знакоместо не
 * помещается, а шрифт его всё равно не нарисует.
 */
constexpr std::uint32_t REPLACEMENT_CHARACTER = 0xFFFD;

/** @brief Шаг табуляции в знакоместах: Tab ведёт курсор к следующему кратному ему столбцу. */
constexpr int TAB_WIDTH = 8;

/**
 * @brief Наибольшее число строк экрана.
 *
 * Изменённые строки экран отмечает разрядами 64-разрядного числа. Строк
 * больше не бывает: даже при 1024 × 768 и шрифте высотой 18 точек их 42.
 */
constexpr int MAX_ROWS = 64;

/**
 * @brief Сколько знакомест вмещает история экрана: 4096 знакомест — 16 КБ.
 *
 * Строки хранятся без пустых знакомест в конце, а строки вывода оболочки
 * обычно короткие, поэтому в историю входит около 100–400 строк.
 */
constexpr int SCROLLBACK_CELLS = 4096;

/** @brief Сколько строк помнит история экрана; список их начал и длин занимает 2 КБ. */
constexpr int SCROLLBACK_ROWS = 512;

/** @brief Номер цвета ANSI для текста по умолчанию — светло-серый (@c SGR 39). */
constexpr std::uint8_t DEFAULT_FOREGROUND = 7;

/** @brief Номер цвета ANSI для фона по умолчанию — чёрный (@c SGR 49). */
constexpr std::uint8_t DEFAULT_BACKGROUND = 0;

/**
 * @brief Цвета ANSI 0–15 в виде 0xRRGGBB — палитра VGA.
 *
 * Порядок — как у последовательностей @c SGR: чёрный, красный, зелёный,
 * жёлтый (коричневый), синий, пурпурный, голубой, светло-серый, затем те же
 * яркие. Уровни каналов (0x00, 0x55, 0xAA, 0xFF) совпадают с уровнями
 * 64-цветного вывода VGA платы, поэтому в 16-цветном режиме цвета
 * передаются точно. По этой таблице экран заменяет цвета из 256 и
 * произвольные цвета RGB ближайшими из 16.
 */
constexpr std::array<std::uint32_t, 16> ANSI_COLORS{
    0x000000, 0xAA0000, 0x00AA00, 0xAA5500, 0x0000AA, 0xAA00AA, 0x00AAAA, 0xAAAAAA,
    0x555555, 0xFF5555, 0x55FF55, 0xFFFF55, 0x5555FF, 0xFF55FF, 0x55FFFF, 0xFFFFFF,
};

}
