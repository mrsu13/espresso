/**
 * @mainpage Espresso
 *
 * Прошивка для платы LilyGO TTGO VGA32 v1.4 (ESP32-PICO-D4, ESP-IDF 6.1).
 * Пока это проверка модулей, полученных из библиотеки FabGL: вывод на VGA
 * (esp::vga), графика (esp::gfx), клавиатура и мышь PS/2 (esp::ps2) и звук
 * (esp::sound). При запуске прошивка выводит в последовательную консоль
 * сведения о плате.
 *
 * Приложение — класс esp::app, проверку FabGL ведёт класс esp::fabgl_test.
 * Оборудование представлено классами esp::button (кнопка) и esp::sd_card
 * (карта памяти); корпус чипа определяет esp::chip_package().
 */

/**
 * @namespace esp
 * @brief Классы и функции прошивки Espresso.
 */

#include "esp_app.h"


/**
 * @brief Точка входа приложения ESP-IDF.
 *
 * Вызывается из главной задачи FreeRTOS после запуска системы. Создаёт
 * приложение и передаёт ему управление.
 */
extern "C" void app_main()
{
    // Приложение размещается в статической памяти, а не на стеке главной
    // задачи: одни объекты FabGL занимают около килобайта, а весь этот
    // стек — 3,5 КБ. exec() не возвращает управление.
    static esp::app app;
    app.exec();
}
