/**
 * @file esp_gfx_rgb222.cpp
 * @brief 6-разрядный цвет: перевод из 24-разрядного.
 */

#include "esp_gfx_rgb222.h"

#include <cstdint>


#pragma GCC optimize("O2")


/**
 * @struct esp::gfx::rgb222
 * @brief Цвет из трёх 2-разрядных каналов — формат пикселя VGA-выхода платы.
 *
 * На каждый канал у VGA-разъёма платы по два вывода, поэтому каналы
 * принимают значения от 0 до 3 (64 цвета). Если выводов по одному на канал
 * (8 цветов), @c low_bit_only равно @c true, и каналы бывают только 0 или
 * 3. Из @c esp::gfx::rgb888 цвет получается отбрасыванием младших
 * разрядов: 0…63 дают 0, 64…127 — 1, 128…191 — 2, 192…255 — 3.
 */


bool esp::gfx::rgb222::low_bit_only = false;


// Открытые

/**
 * @brief Переводит 24-разрядный цвет в 6-разрядный.
 *
 * В режиме 64 цветов канал берёт два старших разряда, в режиме 8 цветов
 * любой ненулевой канал становится 3. Преобразование неявное: драйверы VGA
 * передают цвета холста туда, где ждут формат пикселя.
 *
 * @param value Исходный цвет.
 */
esp::gfx::rgb222::rgb222(const rgb888 &value)
{
    if (low_bit_only)
    {
        r = value.r ? 3 : 0;
        g = value.g ? 3 : 0;
        b = value.b ? 3 : 0;
    }
    else
    {
        r = value.r >> 6;
        g = value.g >> 6;
        b = value.b >> 6;
    }
}

/**
 * @brief Переводит 24-разрядный цвет в упакованный байт RGB222.
 *
 * Байт имеет вид 00BBGGRR — так пиксели хранятся в буфере кадра VGA. В
 * режиме 64 цветов канал берёт два старших разряда, в режиме 8 цветов
 * (@c esp::gfx::rgb222::low_bit_only) любой канал от 64 и выше становится
 * 3. Таблицы дают сразу сдвинутые значения каналов.
 *
 * @param rgb Исходный цвет.
 * @return Упакованный цвет: разряды 0–1 — красный, 2–3 — зелёный, 4–5 —
 *         синий.
 */
std::uint8_t esp::gfx::rgb888_to_packed_rgb222(const rgb888 &rgb)
{
    // 64 цвета: два старших разряда канала (0…63 → 0, 64…127 → 1,
    // 128…191 → 2, 192…255 → 3).
    static const int CONVR64[4] = {0 << 0, 1 << 0, 2 << 0, 3 << 0};
    static const int CONVG64[4] = {0 << 2, 1 << 2, 2 << 2, 3 << 2};
    static const int CONVB64[4] = {0 << 4, 1 << 4, 2 << 4, 3 << 4};
    // 8 цветов: канал от 64 и выше — полная яркость.
    static const int CONVR8[4] = {0 << 0, 3 << 0, 3 << 0, 3 << 0};
    static const int CONVG8[4] = {0 << 2, 3 << 2, 3 << 2, 3 << 2};
    static const int CONVB8[4] = {0 << 4, 3 << 4, 3 << 4, 3 << 4};

    if (rgb222::low_bit_only)
        return (CONVR8[rgb.r >> 6]) | (CONVG8[rgb.g >> 6]) | (CONVB8[rgb.b >> 6]);
    else
        return (CONVR64[rgb.r >> 6]) | (CONVG64[rgb.g >> 6]) | (CONVB64[rgb.b >> 6]);
}
