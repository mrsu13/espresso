#include "esp_app.h"


/**
 * @brief Точка входа приложения ESP-IDF.
 *
 * Вызывается из главной задачи FreeRTOS после запуска системы. Создаёт
 * приложение и передаёт ему управление.
 */
extern "C" void app_main()
{
    // Приложение размещается в статической памяти, а не на стеке главной
    // задачи: один видеоконтроллер занимает около килобайта, а весь этот
    // стек — 3,5 КБ. exec() не возвращает управление.
    static esp::app app;
    app.exec();
}
